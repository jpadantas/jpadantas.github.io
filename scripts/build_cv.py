"""Build the CV PDF from cv/ (local, not versioned) and publish it to files/Joao_Dantas_CV.pdf.

Usage (from the repository root; needs pdflatex and bibtex, e.g. MiKTeX):
    python scripts/build_cv.py

Writes cv/publication_groups.tex from publications.json, so the CV lists publications by type
(Journal Articles, Conference Papers, Theses, Preprints) in the same order as the website,
numbered [J1], [C1], [T1], [P1]. Entries come from cv/publications.bib.
"""
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CV = os.path.join(ROOT, 'cv')
TEX = 'Joao_Dantas_CV'
# publications.json section kind -> (multibib name, heading, label prefix)
GROUPS = {
    'journal': ('jour', 'Journal Articles', 'J'),
    'conference': ('conf', 'Conference Papers', 'C'),
    'thesis': ('thes', 'Theses', 'T'),
    'preprint': ('pre', 'Preprints', 'P'),
}


def write_groups():
    with open(os.path.join(ROOT, 'publications.json'), encoding='utf-8') as f:
        sections = json.load(f)['sections']
    with open(os.path.join(CV, 'publications.bib'), encoding='utf-8') as f:
        cv_keys = set(re.findall(r'^@\w+\{([^,\s]+),', f.read(), re.M))
    site_ids = [item['id'] for s in sections for item in s['items']]
    missing = [i for i in site_ids if i not in cv_keys]
    if missing:
        sys.exit(f'cv/publications.bib has no entry for: {missing}')
    extra = cv_keys - set(site_ids)
    if extra:
        print(f'Warning: in cv/publications.bib but not on the website (left out of the CV): {sorted(extra)}')

    lines = ['% Generated by scripts/build_cv.py from publications.json - do not edit by hand.']
    for section in sections:
        name, heading, prefix = GROUPS[section['kind']]
        keys = ','.join(item['id'] for item in section['items'])
        lines += [f'\\pubgroup{{{heading}}}', f'\\pubprefix{{{prefix}}}', f'\\nocite{name}{{{keys}}}',
                  f'\\bibliographystyle{name}{{unsrt}}', f'\\bibliography{name}{{publications}}', '']
    with open(os.path.join(CV, 'publication_groups.tex'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    return [GROUPS[s['kind']][0] for s in sections]


def run(*cmd):
    result = subprocess.run(cmd, cwd=CV, capture_output=True, text=True, encoding='utf-8', errors='replace')
    return result.returncode, result.stdout


def main():
    groups = write_groups()
    run('pdflatex', '-interaction=nonstopmode', TEX)
    for name in groups:
        code, out = run('bibtex', name)
        warnings = [l for l in out.splitlines() if l.startswith('Warning') or 'error' in l.lower()]
        if code or warnings:
            print(f'bibtex {name}:', *warnings, sep='\n  ')
    for _ in range(2):
        run('pdflatex', '-interaction=nonstopmode', TEX)
    with open(os.path.join(CV, f'{TEX}.log'), encoding='utf-8', errors='replace') as f:
        errors = [l for l in f if l.startswith('! ')]
    if errors:
        sys.exit('LaTeX errors:\n  ' + '  '.join(errors))
    shutil.copyfile(os.path.join(CV, f'{TEX}.pdf'), os.path.join(ROOT, 'files', 'Joao_Dantas_CV.pdf'))
    print('CV built and copied to files/Joao_Dantas_CV.pdf')


if __name__ == '__main__':
    main()
