"""Build css/icons.css + fonts/*.woff2 with only the Font Awesome / Academicons icons this site uses.

Usage (from the repository root; needs internet and `pip install fonttools brotli`):
    python scripts/build_icons.py

Run it again whenever a page starts using an icon that is not in css/icons.css yet.
Replaces the full CDN libraries (~430 KB) with a few KB served from the site itself.
"""
import glob
import io
import os
import re
import sys
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FA = 'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.1'
AI = 'https://cdn.jsdelivr.net/gh/jpswalsh/academicons@1'
FONTS = {  # family key -> (source font URL, output file)
    'solid': (f'{FA}/webfonts/fa-solid-900.woff2', 'fonts/fa-solid-subset.woff2'),
    'brands': (f'{FA}/webfonts/fa-brands-400.woff2', 'fonts/fa-brands-subset.woff2'),
    'ai': (f'{AI}/fonts/academicons.ttf', 'fonts/academicons-subset.woff2'),
}
SOURCES = ['*.html', 'scripts/*.py', 'scripts/templates/*.html']


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'}), timeout=60) as r:
        return r.read()


def used_icons():
    """{'solid': {...}, 'brands': {...}, 'ai': {...}} icon names referenced in the site sources."""
    text = ''
    for pattern in SOURCES:
        for path in glob.glob(os.path.join(ROOT, pattern)):
            if os.path.basename(path) != 'build_icons.py':
                text += open(path, encoding='utf-8').read()
    return {
        'solid': set(re.findall(r'fa-solid fa-([a-z0-9-]+)', text)),
        'brands': set(re.findall(r'fa-brands fa-([a-z0-9-]+)', text)),
        'ai': set(re.findall(r'\bai ai-([a-z0-9-]+)', text)),
    }


def codepoints(css, prefix, names):
    """{name: codepoint} from rules like `.fa-x:before,.fa-y:before{content:"\\f036"}`."""
    found = {}
    for selectors, code in re.findall(r'([^{}]+)\{\s*content:\s*"\\([0-9a-f]+)";?\s*\}', css):
        for name in re.findall(rf'\.{prefix}-([a-z0-9-]+):before', selectors):
            if name in names:
                found[name] = int(code, 16)
    missing = names - found.keys()
    if missing:
        sys.exit(f'Icons not found in the {prefix} stylesheet: {sorted(missing)}')
    return found


def subset_font(url, out, codes):
    font = TTFont(io.BytesIO(fetch(url)))
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = []
    options.name_IDs = ['*']
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted(codes))
    subsetter.subset(font)
    os.makedirs(os.path.join(ROOT, os.path.dirname(out)), exist_ok=True)
    font.flavor = 'woff2'
    font.save(os.path.join(ROOT, out))
    return os.path.getsize(os.path.join(ROOT, out))


def main():
    icons = used_icons()
    fa_css = fetch(f'{FA}/css/all.min.css').decode()
    ai_css = fetch(f'{AI}/css/academicons.min.css').decode()
    codes = {
        'solid': codepoints(fa_css, 'fa', icons['solid']),
        'brands': codepoints(fa_css, 'fa', icons['brands']),
        'ai': codepoints(ai_css, 'ai', icons['ai']),
    }
    sizes = {key: subset_font(url, out, codes[key].values()) for key, (url, out) in FONTS.items()}

    def rules(prefix, mapping):
        return '\n'.join(f'.{prefix}-{name}:before{{content:"\\{cp:x}"}}' for name, cp in sorted(mapping.items()))

    css = f'''/* Generated by scripts/build_icons.py - only the icons used on this site. Do not edit by hand.
   Font Awesome Free 6.5.1 by @fontawesome - https://fontawesome.com (icons CC BY 4.0, fonts SIL OFL 1.1, code MIT)
   Academicons by James Walsh - https://jpswalsh.github.io/academicons/ (SIL OFL 1.1) */
@font-face{{font-family:"Font Awesome 6 Free";font-style:normal;font-weight:900;font-display:block;src:url(../{FONTS['solid'][1]}) format("woff2")}}
@font-face{{font-family:"Font Awesome 6 Brands";font-style:normal;font-weight:400;font-display:block;src:url(../{FONTS['brands'][1]}) format("woff2")}}
@font-face{{font-family:"Academicons";font-style:normal;font-weight:400;font-display:block;src:url(../{FONTS['ai'][1]}) format("woff2")}}
.fa-solid,.fa-brands,.ai{{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:inline-block;font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}}
.fa-solid{{font-family:"Font Awesome 6 Free";font-weight:900}}
.fa-brands{{font-family:"Font Awesome 6 Brands";font-weight:400}}
.ai{{font-family:"Academicons";font-weight:400}}
{rules('fa', {**codes['solid'], **codes['brands']})}
{rules('ai', codes['ai'])}
'''
    with open(os.path.join(ROOT, 'css', 'icons.css'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(css)
    total = sum(sizes.values()) + len(css.encode())
    print(f"{len(codes['solid'])} solid + {len(codes['brands'])} brand + {len(codes['ai'])} academic icons; "
          f"css/icons.css + fonts = {total / 1000:.1f} KB")


if __name__ == '__main__':
    main()
