"""Render awards.json for the website (awards.html) and for the CV (cv/awards_sections.tex).

Item text uses a small markdown: **bold** and [link text](url).
"""
import html
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = 'https://www.joaopadantas.com'
LINK = re.compile(r'\[([^\]]+)\]\(([^)]+)\)')
BOLD = re.compile(r'\*\*(.+?)\*\*')


def load():
    with open(os.path.join(ROOT, 'awards.json'), encoding='utf-8') as f:
        return json.load(f)['sections']


# ---------------------------------------------------------------------------- website

def text_html(text):
    out = html.escape(text, quote=False)
    out = LINK.sub(lambda m: f'<a href="{html.escape(m.group(2))}">{m.group(1)}</a>', out)
    return BOLD.sub(r'<strong>\1</strong>', out)


def item_html(item, indent):
    i = indent
    color = f' icon-{item["color"]}' if item.get('color') else ''
    tags = []
    if item.get('certificate'):
        tags.append(f'<a href="{html.escape(item["certificate"])}" class="cert-tag"><i class="fa-solid fa-certificate"></i> Certificate</a>')
    if item.get('results'):
        tags.append(f'<a href="{html.escape(item["results"])}" class="cert-tag"><i class="fa-solid fa-square-poll-vertical"></i> Results</a>')
    tag_lines = [f'{i}            {t}' for t in tags]
    return '\n'.join([
        f'{i}<div class="award-item reveal">',
        f'{i}    <div class="award-icon{color}"><i class="fa-solid {item["icon"]}"></i></div>',
        f'{i}    <div class="award-content">',
        f'{i}        <span class="award-year">{html.escape(item["date"])}</span>',
        f'{i}        <span class="award-text">',
        f'{i}            {text_html(item["text"])}',
        *tag_lines,
        f'{i}        </span>',
        f'{i}    </div>',
        f'{i}</div>',
    ])


def sections_html(indent='        '):
    blocks = []
    for section in load():
        items = '\n\n'.join(item_html(it, indent + '        ') for it in section['items'])
        blocks.append('\n'.join([
            f'{indent}<section class="publications-section">',
            f'{indent}    <h2 class="section-title">{html.escape(section["title"], quote=False)}</h2>',
            f'{indent}    <div class="awards-list">',
            items,
            f'{indent}    </div>',
            f'{indent}</section>',
        ]))
    return '\n\n'.join(blocks)


# ---------------------------------------------------------------------------- CV (LaTeX)

def _latex_escape(text):
    for ch in '&%$#_{}':
        text = text.replace(ch, '\\' + ch)
    return text.replace('≈', r'$\approx$').replace('—', '---').replace('–', '--')


def _quotes(text):
    return re.sub(r'"([^"]*)"', r"``\1''", text)


def _url(url):
    return url.replace('%', r'\%').replace('#', r'\#')


def text_latex(text):
    text = BOLD.sub(r'\1', text)  # the CV does not use bold inside entries
    parts, last = [], 0
    for m in LINK.finditer(text):
        parts.append(_quotes(_latex_escape(text[last:m.start()])))
        parts.append(f'\\href{{{_url(m.group(2))}}}{{{_latex_escape(m.group(1))}}}')
        last = m.end()
    parts.append(_quotes(_latex_escape(text[last:])))
    return ''.join(parts)


def short_date(date):
    """'December 2025' -> 'Dec 2025'; 'August 2014 — May 2015' -> 'Aug 2014 -- May 2015'."""
    parts = [p.strip() for p in re.split(r'\s+[—–-]\s+', date)]
    short = [re.sub(r'^([A-Z][a-z]{2})[a-z]*', r'\1', p) for p in parts]
    return ' -- '.join(short)


def item_latex(item):
    line = f'\\textbf{{{short_date(item["date"])}:}} {text_latex(item["text"])}'
    if item.get('certificate'):
        line += f'\n\\certlink{{{SITE}/{item["certificate"]}}}'
    if item.get('results'):
        line += f'\n\\resultlink{{{_url(item["results"])}}}'
    return line


def sections_latex():
    out = ['% Generated by scripts/build_cv.py from awards.json - do not edit by hand.']
    for section in load():
        title = section['title'].replace('&', r'\&')
        entries = [item_latex(it) for it in section['items']]
        # One paragraph per entry, with no space between them, and never split across pages
        out += [f'\\begin{{rSection}}{{{title}}}', '\\footnotesize\\setlength{\\parskip}{0pt}\\interlinepenalty=10000',
                '\n\n'.join(entries), '\\end{rSection}', '']
    return '\n'.join(out)
